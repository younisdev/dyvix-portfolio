import type { Metadata } from "next";
import "./globals.css";
import { parseMainConfigVars } from "./utils";
import React from "react";
import { db } from "@/db";
import { configProfiles } from "@/db/schema";
import { eq } from "drizzle-orm";
import path from "path";
import { promises as fs } from "fs";

export async function getActiveConfig() {
  try {
    const [activeProfile] = await db
      .select()
      .from(configProfiles)
      .where(eq(configProfiles.isActive, true))
      .limit(1);
    if (activeProfile?.contentConfig) {
      return parseMainConfigVars(activeProfile.contentConfig);
    }
  } catch (err) {
    console.warn(
      "Failed to load dynamic config from DB, falling back to JSON:",
      err,
    );
  }

  const rawConfig = await getFallbackConfig();

  return parseMainConfigVars(rawConfig);
}

async function getFallbackConfig() {
  const filePath = path.join(process.cwd(), "/dyvix.config.json");
  const rawContent = await fs.readFile(filePath, "utf-8");
  const rawConfig = JSON.parse(rawContent);
  return rawConfig;
}

export async function generateMetadata(): Promise<Metadata> {
  const config = await getActiveConfig();
  return {
    title: `${config?.components?.nav?.header}`,
    description: "Generated by create next app",
  };
}

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const config = await getActiveConfig();
  const backgroundColor = config["backgroundColor"] || "#17160b";
  return (
    <html lang="en" className={`h-full antialiased`}>
      <body
        className="min-h-full flex flex-col"
        style={{ "--background": backgroundColor } as React.CSSProperties}
      >
        {children}
      </body>
    </html>
  );
}
